import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";

const defaultRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Plugins that have both a folder under `plugins/` and a CLI source under `packages/<plugin>/src/main.ts`. */
export function bundledPlugins(root = defaultRoot) {
  const plugins = join(root, "plugins");
  if (!existsSync(plugins)) return [];
  return readdirSync(plugins, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(join(root, "packages", e.name, "src", "main.ts")))
    .map((e) => e.name)
    .sort();
}

export function bundlePath(plugin, root = defaultRoot) {
  return join(root, "plugins", plugin, "dist", `${plugin}.mjs`);
}

export function grammarsPath(plugin, root = defaultRoot) {
  return join(root, "plugins", plugin, "dist", "grammars");
}

/** How the grammar loader's path ends in an esbuild metafile, which gives forward slashes and real paths. */
const GRAMMARS_MODULE = "packages/parse/src/grammars.ts";

/**
 * Bundles `packages/<plugin>` and the workspace packages it imports into one
 * ESM file and returns its text. Node's builtins are the only externals, so
 * the installed plugin needs no `npm install`. `node:sqlite` is loaded at run
 * time by the history package, never imported, so it needs no special case.
 * The output depends only on the sources: no timestamps, sourcemaps or
 * absolute paths, so a rebuild is byte identical.
 */
export async function bundle(plugin, root = defaultRoot) {
  return (await bundleWithInputs(plugin, root)).text;
}

/**
 * A plugin parses when its bundle includes the parse package's grammar loader,
 * directly or through another package. Such a plugin ships the tree-sitter
 * .wasm files in `dist/grammars/`, where that loader finds them relative to
 * `import.meta.url`.
 */
export async function pluginParses(plugin, root = defaultRoot) {
  return (await bundleWithInputs(plugin, root)).parses;
}

/**
 * Lets a bundle include CommonJS packages (ts-morph and the TypeScript compiler it carries) that call `require`
 * for Node's builtins, which an ES module has no `require` for. A bundle gets it only when esbuild had to emit
 * its dynamic-require stub, so the bundles of plugins without such a package stay as they were.
 */
const REQUIRE_SHIM =
  'import { createRequire as __codeHealthCreateRequire } from "node:module"; import { fileURLToPath as __codeHealthFileURLToPath } from "node:url"; import { dirname as __codeHealthDirname } from "node:path"; var require = __codeHealthCreateRequire(import.meta.url); var __filename = __codeHealthFileURLToPath(import.meta.url); var __dirname = __codeHealthDirname(__filename);';

async function bundleWithInputs(plugin, root) {
  const generated = `// Generated by scripts/bundle.mjs from packages/${plugin}. Do not edit; run \`npm run build\`.`;
  const run = (banner) =>
    build({
      absWorkingDir: root,
      entryPoints: [join("packages", plugin, "src", "main.ts")],
      outfile: relative(root, bundlePath(plugin, root)),
      write: false,
      bundle: true,
      platform: "node",
      format: "esm",
      target: "node22",
      external: ["node:*"],
      legalComments: "none",
      charset: "utf8",
      logLevel: "silent",
      metafile: true,
      banner: { js: banner },
    });
  let result = await run(generated);
  if (result.outputFiles[0]?.text.includes("Dynamic require of")) result = await run(`${generated}\n${REQUIRE_SHIM}`);
  const [output] = result.outputFiles;
  if (!output || result.outputFiles.length !== 1) throw new Error(`expected one output file for ${plugin}`);
  const parses = Object.keys(result.metafile.inputs).some((input) => input.endsWith(GRAMMARS_MODULE));
  return { text: output.text, parses };
}

/**
 * Copies the grammar files into `directory` with `copyGrammars` from the parse
 * package, so the build and the package agree on which files a parsing plugin
 * needs. The package is TypeScript, so it is compiled to a throwaway module
 * inside `node_modules`, which lets its own dependencies resolve; node never
 * runs TypeScript here.
 */
async function copyGrammarFiles(directory, root) {
  const scratch = mkdtempSync(join(root, "node_modules", ".copy-grammars-"));
  try {
    const file = join(scratch, "copy-grammars.mjs");
    await build({
      absWorkingDir: root,
      entryPoints: [join("packages", "parse", "src", "copy-grammars.ts")],
      outfile: file,
      bundle: true,
      packages: "external",
      platform: "node",
      format: "esm",
      target: "node22",
      logLevel: "silent",
    });
    const { copyGrammars } = await import(pathToFileURL(file).href);
    return copyGrammars(directory);
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

/** Writes every plugin's bundle. Returns the plugins built. */
export async function buildAll(root = defaultRoot) {
  const plugins = bundledPlugins(root);
  for (const plugin of plugins) {
    const file = bundlePath(plugin, root);
    mkdirSync(dirname(file), { recursive: true });
    const { text, parses } = await bundleWithInputs(plugin, root);
    writeFileSync(file, text);
    if (parses) await copyGrammarFiles(grammarsPath(plugin, root), root);
    else rmSync(grammarsPath(plugin, root), { recursive: true, force: true });
  }
  return plugins;
}

/** The files under `directory` with their bytes, by relative name. Empty when there is no such directory. */
function filesIn(directory) {
  if (!existsSync(directory)) return new Map();
  return new Map(readdirSync(directory).sort().map((name) => [name, readFileSync(join(directory, name))]));
}

/** Plugins whose committed bundle or grammar files differ from a fresh build, or are missing. */
export async function staleBundles(root = defaultRoot) {
  const stale = [];
  for (const plugin of bundledPlugins(root)) {
    const file = bundlePath(plugin, root);
    const { text, parses } = await bundleWithInputs(plugin, root);
    if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
      stale.push(plugin);
      continue;
    }
    const committed = filesIn(grammarsPath(plugin, root));
    if (!parses) {
      if (committed.size > 0) stale.push(plugin);
      continue;
    }
    const scratch = mkdtempSync(join(root, "node_modules", ".grammars-check-"));
    try {
      await copyGrammarFiles(scratch, root);
      const fresh = filesIn(scratch);
      const same = fresh.size === committed.size && [...fresh].every(([name, bytes]) => committed.get(name)?.equals(bytes));
      if (!same) stale.push(plugin);
    } finally {
      rmSync(scratch, { recursive: true, force: true });
    }
  }
  return stale;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = await staleBundles();
    if (stale.length > 0) {
      console.error(`dist is out of date for: ${stale.join(", ")}; run npm run build and commit the result`);
      process.exit(1);
    }
    console.log("dist matches a fresh build");
  } else {
    for (const plugin of await buildAll()) console.log(`bundled plugins/${plugin}/dist/${plugin}.mjs`);
  }
}
