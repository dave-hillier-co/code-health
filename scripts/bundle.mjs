import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";

const defaultRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Plugins that have both a folder under `plugins/` and a CLI source under `packages/<plugin>/src/main.ts`. */
export function bundledPlugins(root = defaultRoot) {
  const plugins = join(root, "plugins");
  if (!existsSync(plugins)) return [];
  return readdirSync(plugins, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(join(root, "packages", e.name, "src", "main.ts")))
    .map((e) => e.name)
    .sort();
}

export function bundlePath(plugin, root = defaultRoot) {
  return join(root, "plugins", plugin, "dist", `${plugin}.mjs`);
}

export function grammarsPath(plugin, root = defaultRoot) {
  return join(root, "plugins", plugin, "dist", "grammars");
}

export function noticesPath(plugin, root = defaultRoot) {
  return join(root, "plugins", plugin, "dist", "THIRD_PARTY_NOTICES.md");
}

/** The suite's own licence, stated in every bundle and notices file. */
const SUITE_LICENCE = "AGPL-3.0-only OR LicenseRef-Commercial";

/** The npm package directory an esbuild metafile input comes from, or null for the repository's own source. */
function packageDirOf(input) {
  const parts = input.split("/");
  const at = parts.lastIndexOf("node_modules");
  if (at < 0) return null;
  const name = parts[at + 1]?.startsWith("@") ? parts.slice(at + 1, at + 3) : parts.slice(at + 1, at + 2);
  return [...parts.slice(0, at + 1), ...name].join("/");
}

const LICENCE_FILE = /^(licen[cs]e|copying|notice)(\.[a-z]+)?$/i;

/**
 * The notices file for a plugin's dist: the suite's licence, then every third-party package the bundle or its
 * grammar files contain, with its version, declared licence and the licence texts the package ships. Permissive
 * licences such as MIT require their notice to travel with every copy, and the bundle strips legal comments.
 */
function thirdPartyNotices(plugin, packageDirs, root) {
  const entries = [...new Set(packageDirs)]
    .map((dir) => {
      const manifest = JSON.parse(readFileSync(join(root, dir, "package.json"), "utf8"));
      const files = readdirSync(join(root, dir)).filter((name) => LICENCE_FILE.test(name)).sort();
      return { name: manifest.name, version: manifest.version, licence: manifest.license ?? "UNKNOWN", texts: files.map((f) => readFileSync(join(root, dir, f), "utf8").trim()) };
    })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const lines = [
    `# Third-party notices for the ${plugin} plugin`,
    "",
    `Generated by scripts/bundle.mjs. Do not edit; run \`npm run build\`.`,
    "",
    `The ${plugin} plugin is copyright David Hillier and licensed under ${SUITE_LICENCE} (see LICENSE and LICENSING.md in the repository). The files in this folder also contain the following third-party packages, each under its own licence.`,
  ];
  for (const entry of entries) {
    lines.push("", `## ${entry.name} ${entry.version}`, "", `Licence: ${entry.licence}`);
    if (entry.texts.length === 0) lines.push("", "The package ships no licence file.");
    for (const text of entry.texts) lines.push("", "```", text, "```");
  }
  return `${lines.join("\n")}\n`;
}

/** How the grammar loader's path ends in an esbuild metafile, which gives forward slashes and real paths. */
const GRAMMARS_MODULE = "packages/parse/src/grammars.ts";

/**
 * Bundles `packages/<plugin>` and the workspace packages it imports into one
 * ESM file and returns its text. Node's builtins are the only externals, so
 * the installed plugin needs no `npm install`. `node:sqlite` is loaded at run
 * time by the history package, never imported, so it needs no special case.
 * The output depends only on the sources: no timestamps, sourcemaps or
 * absolute paths, so a rebuild is byte identical.
 */
export async function bundle(plugin, root = defaultRoot) {
  return (await bundleWithInputs(plugin, root)).text;
}

/**
 * Everything a plugin installs beside its bundle besides grammars: the `chunk-<hash>.mjs` files that
 * `bundle` imports on demand, by file name. A plugin whose commands `import()` a module lazily gets the
 * module, and whatever only it needs, in a chunk, so that a command that never loads it never reads it.
 * Empty for a plugin with no lazily loaded module. Chunks are named for their content, so a rebuild is
 * byte identical and a changed chunk is a new file.
 */
export async function bundleChunks(plugin, root = defaultRoot) {
  return (await bundleWithInputs(plugin, root)).chunks;
}

/**
 * A plugin parses when its bundle includes the parse package's grammar loader,
 * directly or through another package. Such a plugin ships the tree-sitter
 * .wasm files in `dist/grammars/`, where that loader finds them relative to
 * `import.meta.url`.
 */
export async function pluginParses(plugin, root = defaultRoot) {
  return (await bundleWithInputs(plugin, root)).parses;
}

/**
 * Lets a bundle include CommonJS packages (ts-morph and the TypeScript compiler it carries) that call `require`
 * for Node's builtins, which an ES module has no `require` for. A bundle gets it only when esbuild had to emit
 * its dynamic-require stub, so the bundles of plugins without such a package stay as they were.
 */
const REQUIRE_SHIM =
  'import { createRequire as __codeHealthCreateRequire } from "node:module"; import { fileURLToPath as __codeHealthFileURLToPath } from "node:url"; import { dirname as __codeHealthDirname } from "node:path"; var require = __codeHealthCreateRequire(import.meta.url); var __filename = __codeHealthFileURLToPath(import.meta.url); var __dirname = __codeHealthDirname(__filename);';

async function bundleWithInputs(plugin, root) {
  const generated = `// Generated by scripts/bundle.mjs from packages/${plugin}. Do not edit; run \`npm run build\`.\n// SPDX-License-Identifier: ${SUITE_LICENCE}. Third-party licences: THIRD_PARTY_NOTICES.md.`;
  const run = (banner) =>
    build({
      absWorkingDir: root,
      entryPoints: { [plugin]: join("packages", plugin, "src", "main.ts") },
      outdir: relative(root, dirname(bundlePath(plugin, root))),
      outExtension: { ".js": ".mjs" },
      // A module a command loads with `import()` goes in its own file, with the modules only it uses, and
      // is read when the command runs. Without this a rarely needed dependency is parsed on every start.
      splitting: true,
      entryNames: "[name]",
      chunkNames: "chunk-[hash]",
      write: false,
      bundle: true,
      platform: "node",
      format: "esm",
      target: "node22",
      external: ["node:*"],
      legalComments: "none",
      charset: "utf8",
      logLevel: "silent",
      metafile: true,
      banner: { js: banner },
    });
  let result = await run(generated);
  if (result.outputFiles.some((file) => file.text.includes("Dynamic require of"))) result = await run(`${generated}\n${REQUIRE_SHIM}`);
  const main = result.outputFiles.find((file) => basename(file.path) === `${plugin}.mjs`);
  if (!main) throw new Error(`expected ${plugin}.mjs among the output files for ${plugin}`);
  const chunks = new Map(
    result.outputFiles
      .filter((file) => file !== main)
      .map((file) => [basename(file.path), file.text])
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
  );
  const inputs = Object.keys(result.metafile.inputs);
  const parses = inputs.some((input) => input.endsWith(GRAMMARS_MODULE));
  const packageDirs = inputs.map(packageDirOf).filter(Boolean);
  if (parses) packageDirs.push(...(await grammarPackages(root)).map((name) => `node_modules/${name}`));
  return { text: main.text, chunks, parses, notices: thirdPartyNotices(plugin, packageDirs, root) };
}

/**
 * Copies the grammar files into `directory` with `copyGrammars` from the parse
 * package, so the build and the package agree on which files a parsing plugin
 * needs. The package is TypeScript, so it is compiled to a throwaway module
 * inside `node_modules`, which lets its own dependencies resolve; node never
 * runs TypeScript here.
 */
async function copyGrammarFiles(directory, root) {
  return withGrammarModule(root, ({ copyGrammars }) => copyGrammars(directory));
}

/** The npm packages whose grammar files a parsing plugin ships. */
async function grammarPackages(root) {
  return withGrammarModule(root, ({ shippedGrammarPackages }) => shippedGrammarPackages());
}

async function withGrammarModule(root, use) {
  const scratch = mkdtempSync(join(root, "node_modules", ".copy-grammars-"));
  try {
    const file = join(scratch, "copy-grammars.mjs");
    await build({
      absWorkingDir: root,
      entryPoints: [join("packages", "parse", "src", "copy-grammars.ts")],
      outfile: file,
      bundle: true,
      packages: "external",
      platform: "node",
      format: "esm",
      target: "node22",
      logLevel: "silent",
    });
    return use(await import(pathToFileURL(file).href));
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

/** Writes every plugin's bundle. Returns the plugins built. */
export async function buildAll(root = defaultRoot) {
  const plugins = bundledPlugins(root);
  for (const plugin of plugins) {
    const file = bundlePath(plugin, root);
    mkdirSync(dirname(file), { recursive: true });
    const { text, chunks, parses, notices } = await bundleWithInputs(plugin, root);
    writeFileSync(file, text);
    writeFileSync(noticesPath(plugin, root), notices);
    for (const stale of chunkFilesIn(dirname(file))) if (!chunks.has(stale)) rmSync(join(dirname(file), stale));
    for (const [name, chunk] of chunks) writeFileSync(join(dirname(file), name), chunk);
    if (parses) await copyGrammarFiles(grammarsPath(plugin, root), root);
    else rmSync(grammarsPath(plugin, root), { recursive: true, force: true });
  }
  return plugins;
}

/** The names of the chunk files in a plugin's `dist`, sorted. */
function chunkFilesIn(directory) {
  return existsSync(directory) ? readdirSync(directory).filter((name) => /^chunk-.+\.mjs$/.test(name)).sort() : [];
}

/** The files under `directory` with their bytes, by relative name. Empty when there is no such directory. */
function filesIn(directory) {
  if (!existsSync(directory)) return new Map();
  return new Map(readdirSync(directory).sort().map((name) => [name, readFileSync(join(directory, name))]));
}

/** Plugins whose committed bundle or grammar files differ from a fresh build, or are missing. */
export async function staleBundles(root = defaultRoot) {
  const stale = [];
  for (const plugin of bundledPlugins(root)) {
    const file = bundlePath(plugin, root);
    const { text, chunks, parses, notices } = await bundleWithInputs(plugin, root);
    const committedNotices = existsSync(noticesPath(plugin, root)) ? readFileSync(noticesPath(plugin, root), "utf8") : null;
    if (committedNotices !== notices) {
      stale.push(plugin);
      continue;
    }
    const committedChunks = chunkFilesIn(dirname(file));
    const sameChunks = committedChunks.length === chunks.size && committedChunks.every((name) => chunks.get(name) === readFileSync(join(dirname(file), name), "utf8"));
    if (!existsSync(file) || readFileSync(file, "utf8") !== text || !sameChunks) {
      stale.push(plugin);
      continue;
    }
    const committed = filesIn(grammarsPath(plugin, root));
    if (!parses) {
      if (committed.size > 0) stale.push(plugin);
      continue;
    }
    const scratch = mkdtempSync(join(root, "node_modules", ".grammars-check-"));
    try {
      await copyGrammarFiles(scratch, root);
      const fresh = filesIn(scratch);
      const same = fresh.size === committed.size && [...fresh].every(([name, bytes]) => committed.get(name)?.equals(bytes));
      if (!same) stale.push(plugin);
    } finally {
      rmSync(scratch, { recursive: true, force: true });
    }
  }
  return stale;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = await staleBundles();
    if (stale.length > 0) {
      console.error(`dist is out of date for: ${stale.join(", ")}; run npm run build and commit the result`);
      process.exit(1);
    }
    console.log("dist matches a fresh build");
  } else {
    for (const plugin of await buildAll()) console.log(`bundled plugins/${plugin}/dist/${plugin}.mjs`);
  }
}
