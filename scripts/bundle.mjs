import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const defaultRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Plugins that have both a folder under `plugins/` and a CLI source under `packages/<plugin>/src/main.ts`. */
export function bundledPlugins(root = defaultRoot) {
  const plugins = join(root, "plugins");
  if (!existsSync(plugins)) return [];
  return readdirSync(plugins, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(join(root, "packages", e.name, "src", "main.ts")))
    .map((e) => e.name)
    .sort();
}

export function bundlePath(plugin, root = defaultRoot) {
  return join(root, "plugins", plugin, "dist", `${plugin}.mjs`);
}

/**
 * Bundles `packages/<plugin>` and the workspace packages it imports into one
 * ESM file and returns its text. Node's builtins are the only externals, so
 * the installed plugin needs no `npm install`. `node:sqlite` is loaded at run
 * time by the history package, never imported, so it needs no special case.
 * The output depends only on the sources: no timestamps, sourcemaps or
 * absolute paths, so a rebuild is byte identical.
 */
export async function bundle(plugin, root = defaultRoot) {
  const result = await build({
    absWorkingDir: root,
    entryPoints: [join("packages", plugin, "src", "main.ts")],
    outfile: relative(root, bundlePath(plugin, root)),
    write: false,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    external: ["node:*"],
    legalComments: "none",
    charset: "utf8",
    logLevel: "silent",
    banner: { js: `// Generated by scripts/bundle.mjs from packages/${plugin}. Do not edit; run \`npm run build\`.` },
  });
  const [output] = result.outputFiles;
  if (!output || result.outputFiles.length !== 1) throw new Error(`expected one output file for ${plugin}`);
  return output.text;
}

/** Writes every plugin's bundle. Returns the plugins built. */
export async function buildAll(root = defaultRoot) {
  const plugins = bundledPlugins(root);
  for (const plugin of plugins) {
    const file = bundlePath(plugin, root);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, await bundle(plugin, root));
  }
  return plugins;
}

/** Plugins whose committed bundle differs from a fresh build, or is missing. */
export async function staleBundles(root = defaultRoot) {
  const stale = [];
  for (const plugin of bundledPlugins(root)) {
    const file = bundlePath(plugin, root);
    if (!existsSync(file) || readFileSync(file, "utf8") !== (await bundle(plugin, root))) stale.push(plugin);
  }
  return stale;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = await staleBundles();
    if (stale.length > 0) {
      console.error(`dist is out of date for: ${stale.join(", ")}; run npm run build and commit the result`);
      process.exit(1);
    }
    console.log("dist matches a fresh build");
  } else {
    for (const plugin of await buildAll()) console.log(`bundled plugins/${plugin}/dist/${plugin}.mjs`);
  }
}
