import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";
import { defaultRoot, distDir, PLUGIN, tools } from "./layout.mjs";

/** The tools that are bundled: every package with a CLI source at `packages/<tool>/src/main.ts`. */
export const bundledTools = tools;

/** A tool's bundle. Every tool's bundle is in the plugin's one `dist/`, with the chunks, grammars and notices they share. */
export function bundlePath(tool, root = defaultRoot) {
  return join(distDir(root), `${tool}.mjs`);
}

export function grammarsPath(root = defaultRoot) {
  return join(distDir(root), "grammars");
}

export function noticesPath(root = defaultRoot) {
  return join(distDir(root), "THIRD_PARTY_NOTICES.md");
}

/** The suite's own licence, stated in every bundle and notices file. */
const SUITE_LICENCE = "AGPL-3.0-only OR LicenseRef-Commercial";

/** The npm package directory an esbuild metafile input comes from, or null for the repository's own source. */
function packageDirOf(input) {
  const parts = input.split("/");
  const at = parts.lastIndexOf("node_modules");
  if (at < 0) return null;
  const name = parts[at + 1]?.startsWith("@") ? parts.slice(at + 1, at + 3) : parts.slice(at + 1, at + 2);
  return [...parts.slice(0, at + 1), ...name].join("/");
}

const LICENCE_FILE = /^(licen[cs]e|copying|notice)(\.[a-z]+)?$/i;

/**
 * The notices file for the plugin's dist: the suite's licence, then every third-party package the bundles or the
 * grammar files contain, with its version, declared licence and the licence texts the package ships. Permissive
 * licences such as MIT require their notice to travel with every copy, and the bundle strips legal comments.
 */
function thirdPartyNotices(packageDirs, root) {
  const entries = [...new Set(packageDirs)]
    .map((dir) => {
      const manifest = JSON.parse(readFileSync(join(root, dir, "package.json"), "utf8"));
      const files = readdirSync(join(root, dir)).filter((name) => LICENCE_FILE.test(name)).sort();
      return { name: manifest.name, version: manifest.version, licence: manifest.license ?? "UNKNOWN", texts: files.map((f) => readFileSync(join(root, dir, f), "utf8").trim()) };
    })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const lines = [
    `# Third-party notices for the ${PLUGIN} plugin`,
    "",
    `Generated by scripts/bundle.mjs. Do not edit; run \`npm run build\`.`,
    "",
    `The ${PLUGIN} plugin is copyright David Hillier and licensed under ${SUITE_LICENCE} (see LICENSE and LICENSING.md in the repository). The files in this folder also contain the following third-party packages, each under its own licence.`,
  ];
  for (const entry of entries) {
    lines.push("", `## ${entry.name} ${entry.version}`, "", `Licence: ${entry.licence}`);
    if (entry.texts.length === 0) lines.push("", "The package ships no licence file.");
    for (const text of entry.texts) lines.push("", "```", text, "```");
  }
  return `${lines.join("\n")}\n`;
}

/** How the grammar loader's path ends in an esbuild metafile, which gives forward slashes and real paths. */
const GRAMMARS_MODULE = "packages/parse/src/grammars.ts";

/**
 * Bundles `packages/<tool>` and the workspace packages it imports into one
 * ESM file and returns its text. Node's builtins are the only externals, so
 * the installed plugin needs no `npm install`. `node:sqlite` is loaded at run
 * time by the history package, never imported, so it needs no special case.
 * The output depends only on the sources: no timestamps, sourcemaps or
 * absolute paths, so a rebuild is byte identical.
 */
export async function bundle(tool, root = defaultRoot) {
  return (await bundleWithInputs(tool, root)).text;
}

/**
 * What a tool's bundle needs beside it besides grammars: the `chunk-<hash>.mjs` files that
 * `bundle` imports on demand, by file name. A tool whose commands `import()` a module lazily gets the
 * module, and whatever only it needs, in a chunk, so that a command that never loads it never reads it.
 * Empty for a tool with no lazily loaded module. Chunks are named for their content, so a rebuild is
 * byte identical and a changed chunk is a new file.
 */
export async function bundleChunks(tool, root = defaultRoot) {
  return (await bundleWithInputs(tool, root)).chunks;
}

/**
 * A tool parses when its bundle includes the parse package's grammar loader,
 * directly or through another package. When any tool parses, the plugin ships
 * the tree-sitter .wasm files in `dist/grammars/`, where that loader finds
 * them relative to `import.meta.url`.
 */
export async function toolParses(tool, root = defaultRoot) {
  return (await bundleWithInputs(tool, root)).parses;
}

/**
 * Lets a bundle include CommonJS packages (ts-morph and the TypeScript compiler it carries) that call `require`
 * for Node's builtins, which an ES module has no `require` for. A bundle gets it only when esbuild had to emit
 * its dynamic-require stub, so the bundles of tools without such a package stay as they were.
 */
const REQUIRE_SHIM =
  'import { createRequire as __codeHealthCreateRequire } from "node:module"; import { fileURLToPath as __codeHealthFileURLToPath } from "node:url"; import { dirname as __codeHealthDirname } from "node:path"; var require = __codeHealthCreateRequire(import.meta.url); var __filename = __codeHealthFileURLToPath(import.meta.url); var __dirname = __codeHealthDirname(__filename);';

async function bundleWithInputs(tool, root) {
  const generated = `// Generated by scripts/bundle.mjs from packages/${tool}. Do not edit; run \`npm run build\`.\n// SPDX-License-Identifier: ${SUITE_LICENCE}. Third-party licences: THIRD_PARTY_NOTICES.md.`;
  const run = (banner) =>
    build({
      absWorkingDir: root,
      entryPoints: { [tool]: join("packages", tool, "src", "main.ts") },
      outdir: relative(root, distDir(root)),
      outExtension: { ".js": ".mjs" },
      // A module a command loads with `import()` goes in its own file, with the modules only it uses, and
      // is read when the command runs. Without this a rarely needed dependency is parsed on every start.
      splitting: true,
      entryNames: "[name]",
      chunkNames: "chunk-[hash]",
      write: false,
      bundle: true,
      platform: "node",
      format: "esm",
      target: "node22",
      external: ["node:*"],
      legalComments: "none",
      charset: "utf8",
      logLevel: "silent",
      metafile: true,
      banner: { js: banner },
    });
  let result = await run(generated);
  if (result.outputFiles.some((file) => file.text.includes("Dynamic require of"))) result = await run(`${generated}\n${REQUIRE_SHIM}`);
  const main = result.outputFiles.find((file) => basename(file.path) === `${tool}.mjs`);
  if (!main) throw new Error(`expected ${tool}.mjs among the output files for ${tool}`);
  const chunks = new Map(
    result.outputFiles
      .filter((file) => file !== main)
      .map((file) => [basename(file.path), file.text])
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
  );
  const inputs = Object.keys(result.metafile.inputs);
  const parses = inputs.some((input) => input.endsWith(GRAMMARS_MODULE));
  return { text: main.text, chunks, parses, packageDirs: inputs.map(packageDirOf).filter(Boolean) };
}

/**
 * Every tool's bundle, and what they share in `dist/`: the chunks by file name (a chunk is named for its
 * content, so two tools that produce the same chunk produce the same file), whether any tool parses, and
 * the notices for every package any bundle or the grammar files contain.
 */
async function bundleEverything(root) {
  const built = [];
  const chunks = new Map();
  const packageDirs = [];
  let parses = false;
  for (const tool of bundledTools(root)) {
    const one = await bundleWithInputs(tool, root);
    built.push({ tool, text: one.text, chunks: one.chunks });
    for (const [name, text] of one.chunks) chunks.set(name, text);
    packageDirs.push(...one.packageDirs);
    parses ||= one.parses;
  }
  if (parses) packageDirs.push(...(await grammarPackages(root)).map((name) => `node_modules/${name}`));
  return { built, chunks, parses, notices: thirdPartyNotices(packageDirs, root) };
}

/**
 * Copies the grammar files into `directory` with `copyGrammars` from the parse
 * package, so the build and the package agree on which files a parsing tool
 * needs. The package is TypeScript, so it is compiled to a throwaway module
 * inside `node_modules`, which lets its own dependencies resolve; node never
 * runs TypeScript here.
 */
async function copyGrammarFiles(directory, root) {
  return withGrammarModule(root, ({ copyGrammars }) => copyGrammars(directory));
}

/** The npm packages whose grammar files the plugin ships when a tool parses. */
async function grammarPackages(root) {
  return withGrammarModule(root, ({ shippedGrammarPackages }) => shippedGrammarPackages());
}

async function withGrammarModule(root, use) {
  const scratch = mkdtempSync(join(root, "node_modules", ".copy-grammars-"));
  try {
    const file = join(scratch, "copy-grammars.mjs");
    await build({
      absWorkingDir: root,
      entryPoints: [join("packages", "parse", "src", "copy-grammars.ts")],
      outfile: file,
      bundle: true,
      packages: "external",
      platform: "node",
      format: "esm",
      target: "node22",
      logLevel: "silent",
    });
    return use(await import(pathToFileURL(file).href));
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

/** Writes every tool's bundle, their chunks, the grammars and the notices into the plugin's `dist/`. Returns the tools built. */
export async function buildAll(root = defaultRoot) {
  const { built, chunks, parses, notices } = await bundleEverything(root);
  if (built.length === 0) return [];
  const dist = distDir(root);
  mkdirSync(dist, { recursive: true });
  for (const { tool, text } of built) writeFileSync(bundlePath(tool, root), text);
  writeFileSync(noticesPath(root), notices);
  for (const stale of chunkFilesIn(dist)) if (!chunks.has(stale)) rmSync(join(dist, stale));
  for (const [name, chunk] of chunks) writeFileSync(join(dist, name), chunk);
  if (parses) await copyGrammarFiles(grammarsPath(root), root);
  else rmSync(grammarsPath(root), { recursive: true, force: true });
  return built.map(({ tool }) => tool);
}

/** The names of the chunk files in `dist`, sorted. */
function chunkFilesIn(directory) {
  return existsSync(directory) ? readdirSync(directory).filter((name) => /^chunk-.+\.mjs$/.test(name)).sort() : [];
}

/** The files under `directory` with their bytes, by relative name. Empty when there is no such directory. */
function filesIn(directory) {
  if (!existsSync(directory)) return new Map();
  return new Map(readdirSync(directory).sort().map((name) => [name, readFileSync(join(directory, name))]));
}

/**
 * What in the committed `dist/` differs from a fresh build or is missing: a tool by name when its bundle or
 * one of its chunks does, `chunks` for a chunk file no tool produces, and `THIRD_PARTY_NOTICES.md` or
 * `grammars` for those.
 */
export async function staleBundles(root = defaultRoot) {
  const stale = [];
  const { built, chunks, parses, notices } = await bundleEverything(root);
  const dist = distDir(root);
  const same = (file, text) => existsSync(file) && readFileSync(file, "utf8") === text;
  for (const { tool, text, chunks: own } of built) {
    if (!same(bundlePath(tool, root), text) || ![...own].every(([name, chunk]) => same(join(dist, name), chunk))) stale.push(tool);
  }
  if (chunkFilesIn(dist).some((name) => !chunks.has(name))) stale.push("chunks");
  if (built.length > 0 && !same(noticesPath(root), notices)) stale.push("THIRD_PARTY_NOTICES.md");
  const committed = filesIn(grammarsPath(root));
  if (!parses) {
    if (committed.size > 0) stale.push("grammars");
    return stale;
  }
  const scratch = mkdtempSync(join(root, "node_modules", ".grammars-check-"));
  try {
    await copyGrammarFiles(scratch, root);
    const fresh = filesIn(scratch);
    if (fresh.size !== committed.size || ![...fresh].every(([name, bytes]) => committed.get(name)?.equals(bytes))) stale.push("grammars");
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
  return stale;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = await staleBundles();
    if (stale.length > 0) {
      console.error(`dist is out of date for: ${stale.join(", ")}; run npm run build and commit the result`);
      process.exit(1);
    }
    console.log("dist matches a fresh build");
  } else {
    for (const tool of await buildAll()) console.log(`bundled ${relative(defaultRoot, bundlePath(tool))}`);
  }
}
