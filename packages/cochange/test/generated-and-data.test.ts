import { afterAll, beforeAll, expect, test, vi } from "vitest";
import { GitFixture, type Change, type Step } from "@code-health/fixtures/git-fixture";
import { runCochange, runCochangeOnTerminal } from "./support/run.ts";

vi.setConfig({ testTimeout: 180_000 });

const generatedCs = (n: number) => `// <auto-generated>\n//   tool output ${n}\n// </auto-generated>\nclass Api${n} {}\n`;
const handCs = (n: number) => `class Hand {\n    void Run() {\n        if (true) {\n            Work(${n});\n        }\n    }\n}\n`;
const table = (n: number) => `{"rows": ${n}}\n`;
const notes = (n: number) => `# Changes\n\nentry ${n}\n`;

function step(day: number, changes: Change[]): Step {
  return { type: "commit", message: `change ${day}`, date: `2024-03-${String(day).padStart(2, "0")}T10:00:00Z`, changes };
}

let repo: GitFixture;
beforeAll(() => {
  const steps: Step[] = [
    step(1, [
      { op: "add", path: "src/Hand.cs", content: handCs(1) },
      { op: "add", path: "src/api/Api.cs", content: generatedCs(1) },
      { op: "add", path: "data/table.json", content: table(1) },
      { op: "add", path: "CHANGELOG.md", content: notes(1) },
      { op: "add", path: "vendor/lib/lib.js", content: "var lib = 1;\n" },
    ]),
  ];
  for (let day = 2; day <= 6; day++) {
    steps.push(
      step(day, [
        { op: "modify", path: "src/Hand.cs", content: handCs(day) },
        { op: "modify", path: "src/api/Api.cs", content: generatedCs(day) },
        { op: "modify", path: "data/table.json", content: table(day) },
        { op: "modify", path: "CHANGELOG.md", content: notes(day) },
        { op: "modify", path: "vendor/lib/lib.js", content: `var lib = ${day};\n` },
      ]),
    );
  }
  repo = GitFixture.build(steps);
});
afterAll(() => repo.dispose());

const run = async (...argv: string[]) => {
  const { code, stdout, stderr } = await runCochange(repo.path, [...argv, "--limit", "all", "--json"]);
  expect(stderr).toBe("");
  expect(code).toBe(0);
  return JSON.parse(stdout);
};
const pathsOf = (document: { results: { path: string }[] }) => document.results.map((row) => row.path).sort();

test.each(["hotspots", "fixes", "age"])("%s ranks code only, and counts the generated, vendored and non-code files it left out", async (command) => {
  const document = await run(command);
  expect(pathsOf(document)).toEqual(["src/Hand.cs"]);
  expect(document.dropped).toEqual({ generated: 1, vendored: 1, nonCode: 2 });
});

test.each(["hotspots", "fixes", "age"])("%s with --all-files also ranks the non-code files, and still leaves generated and vendored files out", async (command) => {
  const document = await run(command, "--all-files");
  expect(pathsOf(document)).toEqual(["CHANGELOG.md", "data/table.json", "src/Hand.cs"]);
  expect(document.dropped).toEqual({ generated: 1, vendored: 1 });
  expect(document.inputs.allFiles).toBe(true);
});

test("coupling includes the non-code files and labels each side of a pair", async () => {
  const document = await run("coupling", "--min-support", "1");
  const pairs = document.results.map((row: { path: string; pathKind: string; with: string; withKind: string }) => [row.path, row.pathKind, row.with, row.withKind]);
  expect(pairs).toContainEqual(["CHANGELOG.md", "non-code", "data/table.json", "non-code"]);
  expect(pairs).toContainEqual(["CHANGELOG.md", "non-code", "src/Hand.cs", "code"]);
  const names = new Set(document.results.flatMap((row: { path: string; with: string }) => [row.path, row.with]));
  expect(names.has("src/api/Api.cs")).toBe(false);
  expect(names.has("vendor/lib/lib.js")).toBe(false);
  expect(document.dropped).toEqual({ generated: 1, vendored: 1 });
});

test("a table run prints the counts in a notice", async () => {
  const { stdout } = await runCochangeOnTerminal(repo.path, ["hotspots"]);
  expect(stdout).toContain("Notice: omitted 1 generated file, 1 vendored file, 2 non-code files.");
});
