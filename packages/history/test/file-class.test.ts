import { afterEach, beforeEach, expect, test, vi } from "vitest";
import { droppedCounts, resetDropped } from "@code-health/cli-kit/dropped-files";
import { GitFixture, type Change, type Step } from "@code-health/fixtures/git-fixture";
import { classifyFiles, clearHeaderCache, generatedHeaderMarker, generatedPathClassifier, isInVendorDirectory, readBlobHeads } from "../src/file-class.ts";
import { filterHistory } from "../src/noise.ts";
import { readHistory } from "../src/read.ts";
import { refresh } from "../src/refresh.ts";
import { listBlobs } from "../src/tree.ts";

vi.setConfig({ testTimeout: 180_000 });

const fixtures: GitFixture[] = [];
beforeEach(() => {
  resetDropped();
  clearHeaderCache();
});
afterEach(() => {
  for (const f of fixtures.splice(0)) f.dispose();
});

function build(steps: Step[]) {
  const f = GitFixture.build(steps);
  fixtures.push(f);
  return f;
}

const commit = (message: string, day: number, changes: Change[]): Step => ({
  type: "commit",
  message,
  date: `2024-03-${String(day).padStart(2, "0")}T10:00:00Z`,
  changes,
});
const file = (path: string, content = "x\n"): Change => ({ op: "add", path, content });

test.each([
  ["// <auto-generated>\n//   This code was generated by a tool.\n// </auto-generated>\nclass A {}\n", "<auto-generated"],
  ["// Code generated by protoc-gen-go. DO NOT EDIT.\npackage a\n", "Code generated ... DO NOT EDIT"],
  ["/* @generated */\nexport const a = 1;\n", "@generated"],
  ["# @generated by Thrift\nx = 1\n", "@generated"],
  ["// Generated by the protocol buffer compiler.\nsyntax = 1;\n", "Generated by"],
  ["/*\n * DO NOT EDIT\n */\nint a;\n", "DO NOT EDIT"],
])("a header with a standard marker is generated (%#)", (text, marker) => {
  expect(generatedHeaderMarker(text)).toBe(marker);
});

test("a marker counts only in the first lines and only in a comment", () => {
  const body = `${"// filler\n".repeat(25)}// Generated by hand\n`;
  expect(generatedHeaderMarker(body)).toBeUndefined();
  expect(generatedHeaderMarker('const note = "Generated by hand";\n')).toBeUndefined();
  expect(generatedHeaderMarker("package a\n\nfunc F() {}\n")).toBeUndefined();
});

test("minified files and paths with a generated segment are generated by path, and generatedPatterns are laid over them", () => {
  const builtin = generatedPathClassifier([]);
  expect(builtin("web/static/app.min.js")).toBe(true);
  expect(builtin("web/static/site.min.css")).toBe(true);
  expect(builtin("website/cue/reference/components/sinks/generated/vector.cue")).toBe(true);
  expect(builtin("src/generated.ts")).toBeUndefined();
  expect(builtin("src/app.js")).toBeUndefined();
  const configured = generatedPathClassifier(["!generated", "api/generated/**", "util/*Migrations/**"]);
  expect(configured("docs/generated/a.cue")).toBe(false);
  expect(configured("api/generated/client.ts")).toBe(true);
  expect(configured("util/MySqlMigrations/Migrations/2024.cs")).toBe(true);
  expect(configured("web/app.min.js")).toBe(true);
});

test("a vendor directory at any depth makes a path vendored, a file named vendor does not", () => {
  expect(isInVendorDirectory("vendor/x/y.go")).toBe(true);
  expect(isInVendorDirectory("pkg/third_party/lib.c")).toBe(true);
  expect(isInVendorDirectory("src/vendor.ts")).toBe(false);
  expect(isInVendorDirectory("vendor")).toBe(false);
});

test("history drops files whose header at the analysed revision is a generated marker, and counts them", async () => {
  const repo = build([
    commit("add", 1, [
      file("src/api/Gen.cs", "// <auto-generated>\n// tool\n// </auto-generated>\nclass G {}\n"),
      file("zz_generated.deepcopy.go", "// Code generated by deepcopy-gen. DO NOT EDIT.\npackage a\n"),
      file("src/Real.cs", "class R {}\n"),
      file("vendor/lib/x.go", "package x\n"),
    ]),
    commit("touch", 2, [{ op: "modify", path: "src/api/Gen.cs", content: "// <auto-generated>\n// tool\n// </auto-generated>\nclass G2 {}\n" }]),
  ]);
  await refresh(repo.path);
  const result = await filterHistory(repo.path, await readHistory(repo.path));
  expect(result.changes.map((c) => c.files.map((f) => f.path))).toEqual([["src/Real.cs"]]);
  expect(result.filtersApplied.dropped).toMatchObject({ generated: 3, vendored: 1 });
  expect(droppedCounts()).toEqual({ generated: 2, vendored: 1 });
});

test("an attribute that unsets generated or vendored opts a path back in", async () => {
  const repo = build([
    commit("add", 1, [
      file(".gitattributes", "keep.cs -linguist-generated\nvendor/ours.go linguist-vendored=false\n"),
      file("keep.cs", "// <auto-generated>\nclass K {}\n"),
      file("vendor/ours.go", "package ours\n"),
      file("vendor/theirs.go", "package theirs\n"),
    ]),
  ]);
  await refresh(repo.path);
  const result = await filterHistory(repo.path, await readHistory(repo.path));
  expect(result.changes[0]!.files.map((f) => f.path).sort()).toEqual([".gitattributes", "keep.cs", "vendor/ours.go"]);
});

test("an unset linguist-generated attribute keeps a file of a generated folder, and a minified file is generated without reading it", async () => {
  const repo = build([
    commit("add", 1, [
      file(".gitattributes", "docs/generated/** -linguist-generated\n"),
      file("docs/generated/kept.md"),
      file("src/generated/api.ts"),
      file("web/app.min.js"),
      file("src/app.ts"),
    ]),
  ]);
  const blobs = await listBlobs(repo.path, "HEAD");
  const read: string[] = [];
  const classes = await classifyFiles(repo.path, "HEAD", blobs, blobs.map((b) => b.path), {
    read: async (missing) => {
      read.push(...missing.map((m) => m.path));
      return readBlobHeads(repo.path, [...new Set(missing.map((m) => m.blob))]);
    },
  });
  expect([...classes.generated].sort()).toEqual(["src/generated/api.ts", "web/app.min.js"]);
  expect(read.sort()).toEqual([".gitattributes", "src/app.ts"]);
});

test("a blob is read once and its verdict is cached by blob SHA", async () => {
  const header = "// @generated\nclass A {}\n";
  const repo = build([commit("add", 1, [file("a/One.cs", header), file("b/Two.cs", header), file("c/Three.cs", "class C {}\n")])]);
  const blobs = await listBlobs(repo.path, "HEAD");
  const reads: string[][] = [];
  const read = async (missing: readonly { path: string; blob: string }[]) => {
    reads.push(missing.map((m) => m.path));
    return readBlobHeads(repo.path, [...new Set(missing.map((m) => m.blob))]);
  };
  const paths = blobs.map((b) => b.path);
  const first = await classifyFiles(repo.path, "HEAD", blobs, paths, { read });
  expect([...first.generated].sort()).toEqual(["a/One.cs", "b/Two.cs"]);
  await classifyFiles(repo.path, "HEAD", blobs, paths, { read });
  expect(reads).toHaveLength(1);
});
