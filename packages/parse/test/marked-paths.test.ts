import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { GitFixture } from "@code-health/fixtures/git-fixture";
import { droppedCounts, resetDropped } from "@code-health/cli-kit/dropped-files";
import { treeFromRef, treeFromWorkingTree } from "../src/source-tree.ts";

const fixtures: GitFixture[] = [];
afterEach(() => {
  for (const fixture of fixtures.splice(0)) fixture.dispose();
});

function repoWith(files: Record<string, string>): GitFixture {
  const fixture = GitFixture.build([
    {
      type: "commit",
      message: "initial",
      date: "2024-01-01T00:00:00+00:00",
      changes: Object.entries(files).map(([path, content]) => ({ op: "add" as const, path, content })),
    },
  ]);
  fixtures.push(fixture);
  return fixture;
}

const attributes = "dist/** linguist-generated\nthird_party/** linguist-vendored\n";
const files = {
  ".gitattributes": attributes,
  "src/a.ts": "export const a = 1;\n",
  "dist/bundle.js": "var a=1;\n",
  "third_party/lib.js": "var b=2;\n",
};

describe("trees leave out files marked linguist-generated or linguist-vendored", () => {
  it("from a revision", async () => {
    const repo = repoWith(files);
    const tree = await treeFromRef(repo.path, "HEAD");
    expect([...tree.files.keys()]).toEqual([".gitattributes", "src/a.ts"]);
    expect(await tree.read("dist/bundle.js")).toBeUndefined();
  });

  it("from the working tree, including new files under a marked path", async () => {
    const repo = repoWith(files);
    writeFileSync(join(repo.path, "dist/new.js"), "var c=3;\n");
    const tree = await treeFromWorkingTree(repo.path);
    expect([...tree.files.keys()]).toEqual([".gitattributes", "src/a.ts"]);
  });

  it("brings a file back when .gitattributes unsets the attribute for it, which is how a false positive is opted back in", async () => {
    const repo = repoWith({
      ...files,
      ".gitattributes": `${attributes}dist/keep.js -linguist-generated\nthird_party/ours.js linguist-vendored=false\n`,
      "dist/keep.js": "var k=1;\n",
      "third_party/ours.js": "var o=1;\n",
    });
    const tree = await treeFromRef(repo.path, "HEAD");
    expect([...tree.files.keys()]).toEqual([".gitattributes", "dist/keep.js", "src/a.ts", "third_party/ours.js"]);
  });

  it("keeps everything when the repository has no attributes file", async () => {
    const repo = repoWith({ "src/a.ts": "A", "dist/bundle.js": "B" });
    const tree = await treeFromRef(repo.path, "HEAD");
    expect([...tree.files.keys()]).toEqual(["dist/bundle.js", "src/a.ts"]);
  });
});

describe("trees leave out generated headers and vendor directories", () => {
  const generatedCs = "// <auto-generated>\n// tool\n// </auto-generated>\nclass G {}\n";
  const headerFiles = {
    "src/api/Gen.cs": generatedCs,
    "src/Real.cs": "class R {}\n",
    "vendor/lib/x.go": "package x\n",
    "pkg/third_party/y.c": "int y;\n",
  };

  it("from a revision, counting each file left out", async () => {
    resetDropped();
    const repo = repoWith(headerFiles);
    const tree = await treeFromRef(repo.path, "HEAD");
    expect([...tree.files.keys()]).toEqual(["src/Real.cs"]);
    expect(droppedCounts()).toEqual({ generated: 1, vendored: 2 });
  });

  it("from the working tree, including an uncommitted generated file", async () => {
    resetDropped();
    const repo = repoWith(headerFiles);
    writeFileSync(join(repo.path, "src/New.cs"), generatedCs);
    writeFileSync(join(repo.path, "src/Hand.cs"), "class H {}\n");
    const tree = await treeFromWorkingTree(repo.path);
    expect([...tree.files.keys()]).toEqual(["src/Hand.cs", "src/Real.cs"]);
    expect(droppedCounts()).toEqual({ generated: 2, vendored: 2 });
  });
});
