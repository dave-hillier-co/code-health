import { afterAll, beforeAll, expect, test } from "vitest";
import { loadConfig } from "@code-health/cli-kit/config";
import { GitFixture, type Change } from "@code-health/fixtures/git-fixture";
import { localityConfig, readSettings } from "../src/config.ts";
import { loadProject } from "../src/project.ts";

const add = (path: string, content: string): Change => ({ op: "add", path, content });

let repo: GitFixture;
beforeAll(() => {
  repo = GitFixture.build([
    {
      type: "commit",
      message: "Add a Go package with a generated file",
      date: "2024-01-01T09:00:00Z",
      changes: [
        add("go.mod", "module example.com/m\n\ngo 1.22\n"),
        add("a/gen.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage a\n\nfunc Generated() {}\n"),
        add("a/hand.go", "package a\n\nfunc Hand() {}\n"),
      ],
    },
  ]);
});
afterAll(() => repo.dispose());

test("a generated Go file is not a production file", async () => {
  const project = await loadProject(repo.path, "HEAD", readSettings(loadConfig(repo.path, localityConfig)));
  expect(project.production).toEqual(["a/hand.go"]);
});
